def lookup_knowledge(topic: str) -> str:
    """按关键词匹配灾种科普; 无匹配返回全部灾种简介 (纯函数)。"""
    if topic:
        for aliases, (intro, advice) in _KB.items():
            if any(a in topic for a in aliases):
                name = aliases[0]
                return f"【{name}】{intro}\n{advice}"
    # fallback: 全部灾种总览
    parts = []
    for aliases, (intro, advice) in _KB.items():
        parts.append(f"【{aliases[0]}】{intro} {advice}")
    return "\n".join(parts)


@function_tool
def disaster_kb(topic: str) -> str:
    """查询灾害科普知识与出行防范建议。

    Args:
        topic: 灾种关键词, 如「泥石流」「暴雨」「滑坡」; 传空或未知词返回全部灾种总览。
    Returns:
        科普 + 出行防范文本。
    """
    return lookup_knowledge(topic)
